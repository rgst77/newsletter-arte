import unittest

from contratos.esquemas import FlashcardNewsletter, ImagenObra
from plantillas.email import renderizar_html


def _flashcard(n_imagenes: int) -> FlashcardNewsletter:
    imagenes = [
        ImagenObra(titulo_obra=f"Obra {i}", url_imagen=f"https://x/{i}.jpg", url_fuente="https://x", fuente="Commons", creditos="PD")
        for i in range(n_imagenes)
    ]
    return FlashcardNewsletter(
        nombre="Ana & Co", nacionalidad="Spanish", disciplina="pintura", siglo="siglo XXI",
        corriente="X", periodo="1990-", biografia="Bio.", imagenes=imagenes,
    )


class TestNotaPocasImagenes(unittest.TestCase):
    def test_con_tres_imagenes_no_hay_nota(self):
        self.assertNotIn("We usually share three images", renderizar_html(_flashcard(3)))

    def test_con_una_imagen_aparece_en_singular(self):
        h = renderizar_html(_flashcard(1))
        self.assertIn("We usually share three images per issue. Only one public-domain or freely-licensed", h)
        self.assertIn("image of Ana &amp; Co could be found", h)

    def test_con_dos_imagenes_aparece_en_plural(self):
        h = renderizar_html(_flashcard(2))
        self.assertIn("Only two public-domain or freely-licensed", h)
        self.assertIn("images of Ana &amp; Co could be found", h)

    def test_la_nota_va_despues_de_las_imagenes_y_antes_del_pie(self):
        h = renderizar_html(_flashcard(2))
        self.assertLess(h.index("Obra 1"), h.index("We usually share"))
        self.assertLess(h.index("We usually share"), h.index("generated by an AI research pipeline"))


if __name__ == "__main__":
    unittest.main()
